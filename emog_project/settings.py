def _fastest_tier_name(tiers):
    """Return the tier with the highest 'speed' rating (ties: lowest tier index)."""
    if not tiers:
        return None
    order = ["lite", "fast", "standard", "high", "ultra"]
    return max(
        tiers,
        key=lambda name: (tiers[name].get("speed", 0), -order.index(name) if name in order else 0),
    )


